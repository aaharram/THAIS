import { z } from 'zod';

export const MembersRequestSchema = z.object({
  addUser: z.number().int().nullable(),
  modUser: z.number().int().nullable(),
  username: z.string(),
  password: z.string(),
  firstName: z.string(),
  lastName: z.string(),
  name: z.string(),
  email: z.string(),
  address: z.string(),
  tel: z.string(),
  noCountry: z.number().int(),
  noProvince: z.number().int(),
  noCity: z.number().int(),
  active: z.boolean().nullable(),
  enabled: z.boolean(),
  salaireHoraire: z.number().nullable().optional(),
  noGestionnaire: z.number().int().nullable().optional(),
  patrimoineType: z.number().int().nullable().optional(),
  gestionMetier: z.boolean().optional(),
  gestionFinanciere: z.boolean().optional(),
  gestionAdministrative: z.boolean().optional(),
});

export const MembersResponseSchema = z.object({
  numero: z.number().int(),
  addUser: z.number().int().nullable(),
  nameAddUser: z.string().nullable(),
  addDate: z.string(),
  modUser: z.number().int().nullable(),
  nameModUser: z.string().nullable(),
  modDate: z.string(),
  username: z.string(),
  password: z.string(),
  firstName: z.string(),
  lastName: z.string(),
  name: z.string(),
  email: z.string(),
  address: z.string(),
  tel: z.string(),
  noCountry: z.number().int(),
  nameCountry: z.string().nullable(),
  noProvince: z.number().int(),
  nameProvince: z.string().nullable(),
  noCity: z.number().int(),
  nameCity: z.string().nullable(),
  active: z.boolean().nullable(),
  lastLogin: z.string(),
  lastHit: z.date(),
  dateDebutAbsence: z.string().nullable(),
  dateFinAbsence: z.string().nullable(),
  enabled: z.boolean(),
  salaireHoraire: z.number().nullable().optional(),
  statut: z.enum(['AVAILABLE', 'ON_THE_MOVE', 'ON_BREAK', 'NOT_AVAILABLE']),
  noGestionnaire: z.number().int().nullable().optional(),
  nomGestionnaire: z.string().nullable().optional(),
  patrimoineType: z.number().int().nullable().optional(),
  nomPatrimoineType: z.string().nullable().optional(),
  signatureUrl: z.string().nullable().optional(),
  gestionMetier: z.boolean().optional(),
  gestionFinanciere: z.boolean().optional(),
  gestionAdministrative: z.boolean().optional(),
});

export type MembersResponse = z.infer<typeof MembersResponseSchema>;
export type MembersRequest = z.infer<typeof MembersRequestSchema>;
